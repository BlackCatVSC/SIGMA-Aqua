CREATE TABLE EMPRESA (
    ID_EMPRESA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_EMPRESA VARCHAR2(100) NOT NULL,
    RUT_EMPRESA VARCHAR2(13) NOT NULL,
    DIRECCION_EMPRESA VARCHAR2(100),
    TELEFONO_EMPRESA VARCHAR2(12),
    CORREO_EMPRESA VARCHAR2(50)
);
CREATE TABLE CENTRO_CULTIVO(
    ID_CENTRO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EMPRESA NUMBER NOT NULL,
    NOMBRE_CENTRO VARCHAR2(100) NOT NULL,
    UBICACION_CENTRO VARCHAR2(100) NOT NULL,
    VOLUMEN_CENTRO_M3 NUMBER NOT NULL,
    DENSIDAD_MAXIMA_KG_M3 NUMBER NOT NULL,
    ESTADO_CENTRO VARCHAR2(10),

    CONSTRAINT FK_CENTRO_EMPRESA
        FOREIGN KEY (ID_EMPRESA)
        REFERENCES EMPRESA(ID_EMPRESA)
);


CREATE TABLE ESPECIE(
    ID_ESPECIE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_COMUN VARCHAR2(15) NOT NULL,
    NOMBRE_CIENTIFICO VARCHAR2(20) NOT NULL
);

CREATE TABLE VETERINARIO(
    ID_VETERINARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUT_VETERINARIO VARCHAR2(12) NOT NULL,
    REGISTRO_PROFESIONAL VARCHAR2(20) NOT NULL,
    NOMBRE_VETERINARIO VARCHAR2(12) NOT NULL,
    APELLIDO_VETERINARIO VARCHAR2(12) NOT NULL,
    EMAIL VARCHAR2(30),
    TELEFONO VARCHAR2(12),
    TIPO_CONTRATO VARCHAR2(20),
    ESPECIALIDAD VARCHAR2(50)
    FIRMA_DIGITAL LONGBLOB,
    ESTADO VARCHAR2(10) NOT NULL,
    FECHA_CONTRATO DATE NOT NULL

    CONSTRAINT FK_VETERINARIO_CENTRO
        FOREIGN KEY (ID_CENTRO)
        REFERENCES CENTRO_CULTIVO(ID_CENTRO)
);

