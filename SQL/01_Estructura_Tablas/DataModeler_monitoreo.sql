-- ================================================================================
-- 1. TABLAS DEL DOMINIO DE MONITOREO
-- ================================================================================

-- Tanque / jaula de cultivo monitoreada (pertenece a un centro de cultivo)
CREATE TABLE TANQUE (
    ID_TANQUE           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_TANQUE       VARCHAR2(50)  NOT NULL,
    VOLUMEN_TANQUE_M3   NUMBER,
    ESTADO_TANQUE       VARCHAR2(20),
    ID_CENTRO           NUMBER NOT NULL,
    CONSTRAINT FK_TANQUE_CENTRO
        FOREIGN KEY (ID_CENTRO) REFERENCES CENTRO_CULTIVO(ID_CENTRO)
);

-- Catalogo de tipos de sensor (parametro fisico/quimico medido)
CREATE TABLE TIPO_SENSOR (
    ID_TIPO_SENSOR       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_TIPO_SENSOR   VARCHAR2(50) NOT NULL,
    UNIDAD_MEDIDA        VARCHAR2(20)
);

-- Sensor fisico instalado en un tanque
CREATE TABLE SENSOR (
    ID_SENSOR            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_SENSOR        VARCHAR2(100) NOT NULL,
    ESTADO_SENSOR        VARCHAR2(20),
    FECHA_INSTALACION    DATE,
    ID_TIPO_SENSOR       NUMBER NOT NULL,
    ID_TANQUE            NUMBER NOT NULL,
    CONSTRAINT FK_SENSOR_TIPO
        FOREIGN KEY (ID_TIPO_SENSOR) REFERENCES TIPO_SENSOR(ID_TIPO_SENSOR),
    CONSTRAINT FK_SENSOR_TANQUE
        FOREIGN KEY (ID_TANQUE) REFERENCES TANQUE(ID_TANQUE)
);

-- Umbrales (limites) configurados por tipo de sensor.
-- ID_CENTRO NULL = umbral general; si existe uno especifico para el centro, manda este.
CREATE TABLE UMBRAL (
    ID_UMBRAL           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VALOR_MIN           NUMBER,
    VALOR_MAX           NUMBER,
    SEVERIDAD           VARCHAR2(20),
    ID_TIPO_SENSOR      NUMBER NOT NULL,
    ID_CENTRO           NUMBER,
    CONSTRAINT FK_UMBRAL_TIPO
        FOREIGN KEY (ID_TIPO_SENSOR) REFERENCES TIPO_SENSOR(ID_TIPO_SENSOR),
    CONSTRAINT FK_UMBRAL_CENTRO
        FOREIGN KEY (ID_CENTRO) REFERENCES CENTRO_CULTIVO(ID_CENTRO)
);

-- Buffer temporal de lecturas crudas (se procesan en bloque y se purgan)
CREATE TABLE MEDICIONES_STAGING (
    ID_STAGING          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SENSOR           NUMBER NOT NULL,
    ID_CENTRO           NUMBER NOT NULL,   -- desnormalizado para filtrar por instalacion
    VALOR               NUMBER NOT NULL,
    FECHA_HORA          DATE   NOT NULL,
    ESTADO_PROCESO      VARCHAR2(20),
    CONSTRAINT FK_STAG_SENSOR
        FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR(ID_SENSOR),
    CONSTRAINT FK_STAG_CENTRO
        FOREIGN KEY (ID_CENTRO) REFERENCES CENTRO_CULTIVO(ID_CENTRO)
);

-- Historico definitivo de mediciones (recibe las lecturas procesadas)
CREATE TABLE HISTORIAL_MEDICIONES (
    ID_MEDICION         NUMBER PRIMARY KEY,
    ID_SENSOR           NUMBER NOT NULL,
    VALOR               NUMBER NOT NULL,
    FECHA_HORA          DATE   NOT NULL,
    ESTADO_MEDICION     VARCHAR2(20),
    CONSTRAINT FK_HIST_SENSOR
        FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR(ID_SENSOR)
);

-- Ultimo estado conocido por tanque (una fila por tanque). Lo consume fn_calcular_ica.
CREATE TABLE ULTIMAS_MEDICIONES (
    ID_TANQUE           NUMBER PRIMARY KEY,
    VALOR_PH            NUMBER,
    VALOR_OXIGENO       NUMBER,
    VALOR_TEMPERATURA   NUMBER,
    VALOR_SALINIDAD     NUMBER,
    VALOR_TURBIDEZ      NUMBER,
    FECHA_ACTUALIZACION DATE,
    CONSTRAINT FK_ULT_TANQUE
        FOREIGN KEY (ID_TANQUE) REFERENCES TANQUE(ID_TANQUE)
);

-- Alertas generadas automaticamente cuando una lectura esta fuera de rango
CREATE TABLE ALERTA (
    ID_ALERTA           NUMBER PRIMARY KEY,
    ID_SENSOR           NUMBER NOT NULL,
    ID_MEDICION         NUMBER,
    ID_TIPO_SENSOR      NUMBER,
    VALOR               NUMBER,
    VALOR_MIN           NUMBER,
    VALOR_MAX           NUMBER,
    SEVERIDAD           VARCHAR2(20),
    MENSAJE             VARCHAR2(300),
    FECHA_ALERTA        DATE,
    ESTADO_ALERTA       VARCHAR2(20),
    CONSTRAINT FK_ALERTA_SENSOR
        FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR(ID_SENSOR),
    CONSTRAINT FK_ALERTA_MED
        FOREIGN KEY (ID_MEDICION) REFERENCES HISTORIAL_MEDICIONES(ID_MEDICION),
    CONSTRAINT FK_ALERTA_TIPO
        FOREIGN KEY (ID_TIPO_SENSOR) REFERENCES TIPO_SENSOR(ID_TIPO_SENSOR)
);

-- Acciones correctivas asociadas a una alerta
CREATE TABLE ACCION_CORRECTIVA (
    ID_ACCION           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPCION_ACCION  VARCHAR2(300),
    ESTADO_ACCION       VARCHAR2(20),
    FECHA_ACCION        DATE,
    ID_ALERTA           NUMBER NOT NULL,
    ID_TRABAJADOR       NUMBER,
    CONSTRAINT FK_ACC_ALERTA
        FOREIGN KEY (ID_ALERTA) REFERENCES ALERTA(ID_ALERTA),
    CONSTRAINT FK_ACC_TRAB
        FOREIGN KEY (ID_TRABAJADOR) REFERENCES TRABAJADOR(ID_TRABAJADOR)
);

